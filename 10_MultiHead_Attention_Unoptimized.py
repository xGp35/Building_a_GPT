import torch
import torch.nn as nn
import torch.nn.functional as F

class MultiHeadSelfAttention(nn.Module):
    def __init__(self, embedding_dim, attention_dim, num_heads):
        super().__init__()
        # Create num_heads SingleHeadAttention using nn.ModuleList
        # head_size = attention_dim // num_heads
        # Projection layer W_O, is nn.Linear with bias = False
        assert attention_dim % num_heads == 0
        self.head_size = attention_dim // num_heads
        self.attention_heads = nn.ModuleList([self.SingleHeadAttention(embedding_dim, self.head_size) for _ in range(num_heads)])
        self.W_O = nn.Linear(attention_dim, embedding_dim, bias = False)

    def forward(self, embedded):
        # embedded is [B, T, C]
        # Output of each head is [B, T, d_k]
        # Output of MHA is [B,T, A] before W_O, [B,T, C] after W_O
        # I am calling attention_dim as A, ie [B, T, A] for simplicity. Note this A is different from the actual Attention Matrix A in Single Head Attention. This is just hyperparameter A.
        catted = torch.cat([attention_head(embedded) for attention_head in self.attention_heads], dim = 2) # Shape = [B, T, A]
        result = self.W_O(catted) # This does catted @ W_O^T
        # catted is [B, T, A], W_O is stored as [C, A], so catted @ W_O^T gives [B, T, A] @ [A, C] -> [B, T, C]
        # result will be of dimension - [B, T, C]

        return result

    class SingleHeadAttention(nn.Module):

        def __init__(self, embedding_dim, head_size):
            super().__init__()
            self.C = embedding_dim
            self.d_k = head_size
            self.W_K = nn.Linear(self.C, self.d_k, bias = False)
            self.W_Q = nn.Linear(self.C, self.d_k, bias = False)
            self.W_V = nn.Linear(self.C, self.d_k, bias = False)

        def forward(self, embedded):
            # This will do on a batch [B, T, C]
            # Step 1 - Convert weights to K, Q, V
            K = self.W_K(embedded) # Shape = [B, T, d_k]
            Q = self.W_Q(embedded) # Shape = [B, T, d_k]
            V = self.W_V(embedded) # Shape = [B, T, d_k]

            B, T, d_k = K.shape

            # Step 2 - Create the attention matrix
            attention_matrix = Q @ K.transpose(-2, -1) # Shape = [B, T, T]
            attention_scores = attention_matrix / (d_k ** 0.5)

            # Step 3 - Create the causal mask and apply it
            pre_mask = torch.tril(torch.ones(T, T, device=embedded.device)) # Shape = [T, T]
            mask = (pre_mask == 0)
            masked_attention = attention_scores.masked_fill(
                mask, value= float('-inf')
            ) # Shape = [B, T, T]

            # Step 4 - Apply softmax
            A = F.softmax(masked_attention, dim = -1) # Shape = [B, T, T]

            # Step 5 - Matrix Multiply with Value Vector to get Z
            Z = A @ V # Shape = [B, T, d_k]

            return Z

